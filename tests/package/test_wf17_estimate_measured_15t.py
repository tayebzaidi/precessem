"""`WF-17` step 52 (§9 item 980, §10 U162): measured 1.5 T box-window prices on the estimates page.

Brief: docs/planning/chunks/WF-17.md, "§9 item 980".  No mesh; run under
``mpiexec -n 2``.  The section is generated by
``scripts/docs/generate_estimate_page.py`` (``render_measured`` with the 1.5 T
keywords) and sits between the 14-row table and the 3 T section of
``docs/guide/estimates.md``; the 3 T module (step 47 / 51) is not edited.

Asserted (no band set):
  (X-ledger) ``ledger_prices(entries=MEASURED_15T)`` strings for entries 48 / 52 / 59,
             and custody against each tracked log (the 3 T module's ``_custody``).
  (K15)      the FC1 row: rc 0, CLI = API by ``repr`` (differ ``set()``),
             ``rows_used == ("FC1",)``, ranks / seconds / GiB equal
             ``PRICE_TABLE_CLINICAL[0]``'s.
  (Sec15)    the tracked text from the 1.5 T heading up to the 3 T heading equals
             the fresh 1.5 T render plus the one ``"\\n"`` separator ``render`` adds.
  (Tag15)    ``TAG403_15T``'s keys are exactly the 1.5 T entries, every value ASCII, and
             disjoint from ``TAG403``'s (no entry tagged at both field strengths;
             re-posed by item 982, 03:00 11-14 ruling option (i)).
  (Order)    the 14-row table's last row < the 1.5 T heading < the 3 T heading (the count runs from the page title to the first ``## `` after it; U163).
Negative controls (asserted): (c-52) entry 52's seconds 868 -> 869 in a tmp ledger
passes the shape check and fails custody on entry 52 only; (c-3T) the 1.5 T dict's
``rows_used`` is not ``("FC3",)`` and the 3 T dict's is not ``("FC1",)``.
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

from mpi4py import MPI

from tests.package.test_wf13_cli_estimate import _diff, _parse
from tests.package.test_wf17_estimate_measured_3t import _custody, _ledger_with, _p0
from tests.package.test_wf17_estimate_table_page import gen

ROOT = Path(__file__).resolve().parent.parent.parent
PAGE = ROOT / "docs" / "guide" / "estimates.md"

EXPECTED_15T = {
    "48": ("8", "1 217 025", "42.39", "1052"),
    "52": ("8", "1 217 025", "40.95", "868"),
    "59": ("8", "1 217 025", "41.70", "852"),
}


def test_wf17_s52_ledger_strings_and_custody():
    prices = gen.ledger_prices(entries=gen.MEASURED_15T)
    got = {p["entry"]: (p["ranks"], p["cells"], p["gib"], p["seconds"]) for p in prices}
    custody = _custody(prices)
    for p in prices:
        _p0(f"\n[WF-17 s52] (X-ledger) entry {p['entry']} {p['chunk']} `{p['log']}`: ranks "
            f"{p['ranks']!r} cells {p['cells']!r} GiB {p['gib']!r} seconds {p['seconds']!r}; "
            f"custody failures {custody[p['entry']]}")
    assert [p["entry"] for p in prices] == ["48", "52", "59"]
    assert got == EXPECTED_15T
    assert custody == {"48": [], "52": [], "59": []}


def test_wf17_s52_tag403_keys():
    keys = set(gen.TAG403_15T)
    entries = {e for e, _, _ in gen.MEASURED_15T}
    _p0(f"\n[WF-17 s52] (Tag15) TAG403_15T {gen.TAG403_15T!r}; MEASURED_15T entries "
        f"{sorted(entries)}; TAG403 keys {sorted(gen.TAG403)}")
    assert keys == entries
    assert all(v.isascii() for v in gen.TAG403_15T.values())
    assert keys.isdisjoint(gen.TAG403)


def test_wf17_s52_c52_custody_fails_on_entry52(tmp_path):
    text = gen.LEDGER.read_text(encoding="utf-8")
    row52 = next(ln for ln in text.splitlines() if ln.startswith("| 2026-11-03 | GEO-38-C6 | "))
    cells = row52.split(" | ")
    assert cells[6] == "868"
    cells[6] = "869"
    planted = _ledger_with(tmp_path, row52, " | ".join(cells))
    prices = gen.ledger_prices(planted, entries=gen.MEASURED_15T)
    custody = _custody(prices)
    _p0(f"\n[WF-17 s52] (c-52) seconds {[p['seconds'] for p in prices]}; custody {custody}")
    assert [p["seconds"] for p in prices] == ["1052", "869", "852"]
    assert custody["48"] == [] and custody["59"] == []
    assert custody["52"] and all("seconds" in b for b in custody["52"])


def test_wf17_s52_fc1_row_section_and_order():
    from fem_em_solver.study import PRICE_TABLE_CLINICAL, ResourceEstimate

    comm = MPI.COMM_WORLD
    measured = gen.measured_3t(comm, fc_file=gen.FC15_FILE, entries=gen.MEASURED_15T)
    measured_3t = gen.measured_3t(comm)
    row = measured["row"]
    est = row["est"]
    names = [f.name for f in dataclasses.fields(ResourceEstimate)]
    parsed = _parse(row["stdout"], names)
    complete = set(parsed) == set(names) and all(len(v) == 1 for v in parsed.values())
    differ = _diff(parsed, est) if complete else None
    rcs = comm.allgather(row["rc"])
    pin = PRICE_TABLE_CLINICAL[0]
    pr = row["printed"]
    _p0(f"\n[WF-17 s52] (K15) {row['label']}: rc per rank {rcs}; complete={complete} "
        f"differ={differ}; rows_used={est.rows_used!r}; printed ranks {pr['ranks']!r} "
        f"seconds {pr['predicted_seconds']!r} GiB {pr['predicted_peak_gib']!r} "
        f"cells {pr['cells']!r} (brief's prediction 49.07 / 203.3)")
    for r in measured["ratios"]:
        _p0(f"[WF-17 s52] ratio entry {r['entry']}: GiB {r['gib']} seconds {r['seconds']} "
            "(estimator / measured; a record)")
    _p0(f"[WF-17 s52] (c-3T) 1.5 T rows_used {est.rows_used!r}; "
        f"3 T rows_used {measured_3t['row']['est'].rows_used!r}")

    tracked = PAGE.read_text(encoding="utf-8")
    lines = tracked.splitlines()
    fresh = gen.render_measured(measured, gen.MEASURED_15T_HEADING, "1.5 T", gen.FC15_MESH,
                               tags=gen.TAG403_15T)
    pos15 = tracked.find(gen.MEASURED_15T_HEADING)
    pos3 = tracked.find(gen.MEASURED_HEADING)
    section = tracked[pos15:pos3] if 0 <= pos15 < pos3 else ""
    _p0(f"[WF-17 s52] (Sec15) headings at {pos15} / {pos3}; section {len(section)} chars vs "
        f"fresh {len(fresh)} + 1; equal={section == fresh + chr(10)}")
    i15 = lines.index(gen.MEASURED_15T_HEADING) if gen.MEASURED_15T_HEADING in lines else -1
    i3 = lines.index(gen.MEASURED_HEADING) if gen.MEASURED_HEADING in lines else -1
    # The 14-row table's rows: every "| `" line between the table's own heading (the page's
    # `# ` title) and the first `## ` heading after it (U163, the 11-14 weekly's ruling).
    top = lines.index("# Resource estimates for the shipped study files")
    cut = next((i for i in range(top + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    table_rows = [i for i in range(top + 1, cut) if lines[i].startswith("| `")]
    last_table = table_rows[-1] if table_rows else -1
    _p0(f"[WF-17 s52] (Order) table rows {len(table_rows)}, last at line {last_table}; "
        f"1.5 T heading line {i15}; 3 T heading line {i3}")

    gates = {
        "K15 rc": rcs == [0] * comm.size,
        "K15 CLI=API": complete and differ == set(),
        "K15 rows_used": est.rows_used == ("FC1",),
        "K15 ranks": est.ranks == pin["ranks"],
        "K15 seconds": est.predicted_seconds == pin["seconds"],
        "K15 GiB": est.predicted_peak_gib == pin["peak_gib"],
        "K15 strings": (pr["ranks"], pr["predicted_seconds"], pr["predicted_peak_gib"])
        == ([repr(est.ranks)], [repr(est.predicted_seconds)], [repr(est.predicted_peak_gib)]),
        "c-3T": est.rows_used != ("FC3",) and measured_3t["row"]["est"].rows_used != ("FC1",),
        "Sec15": tracked.count(gen.MEASURED_15T_HEADING) == 1 and section == fresh + "\n",
        "Order": len(table_rows) == 14 and 0 <= last_table < i15 < i3,
    }
    _p0(f"[WF-17 s52] gates {gates}")
    assert all(gates.values()), {k: v for k, v in gates.items() if not v}
