"""`WF-17` step 47 (§9 item 961, §10 U157): measured 3 T box-window prices on the estimates page.

Brief: docs/planning/chunks/WF-17.md, "§9 item 961".  No mesh; run under
``mpiexec -n 2``.  The section is generated by
``scripts/docs/generate_estimate_page.py`` (``render_measured``); the page is
``docs/guide/estimates.md``.

Asserted (no band set):
  (X-ledger) ``ledger_prices()`` strings for entries 58 / 60, and custody against
             each tracked log: seconds == the footer's ``- Elapsed (s):``
             integer; GiB == ``f"{peak / 2**30:.2f}"`` of ``[XL] memory.peak bytes:``.
  (K)        the FC3 row: rc 0, CLI = API by ``repr``, ``rows_used == ("FC3",)``,
             ranks / seconds / GiB equal ``PRICE_TABLE_CLINICAL_3T[-1]``'s, the
             printed strings ``'16'`` / ``'135.1'`` / ``'39.39'`` (U118's pin,
             ``test_wf13_estimate_f_clinical_3t.py:87-90``).
  (Sec)      the tracked page's section (heading to the next ``## `` heading or EOF; U163) equals a fresh
             ``render_measured(measured_3t(comm))`` byte for byte.
Negative controls (asserted): (c-15) the 1.5 T file through the same builder
reads FC1, 203.3 s; (c-ledger) entry 60's seconds 732 -> 733 in a tmp ledger
passes the shape check and fails custody on entry 60 only; (c-shape) a GiB cell
without ``**`` raises ``GenerationError`` naming the entry.
The (Page) gate is the S30 W1 node; (D) is the Wdoc-refs window.

Step 51 (§9 item 977, §10 U161) adds entry 61 to ``EXPECTED`` and the custody
check, (Tag) ``set(TAG403) == MEASURED_3T``'s entries, and (c-61): entry 61's
seconds 848 -> 849 fails custody on entry 61 only.  (c-ledger)'s planted
ledger now parses three entries, so its seconds list gains entry 61's ``"848"``.
"""

from __future__ import annotations

