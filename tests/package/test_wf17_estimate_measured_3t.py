ROOT = Path(__file__).resolve().parent.parent.parent
PAGE = ROOT / "docs" / "guide" / "estimates.md"
LOGS = ROOT / "docs" / "testing" / "logs"
FC15 = ROOT / "tests" / "package" / "wf13" / "f_clinical_15t.yaml"

EXPECTED = {
    "58": ("8", "1 128 430", "33.48", "780"),
    "60": ("8", "1 128 430", "32.75", "732"),
    "61": ("8", "1 128 430", "34.23", "848"),  # step 51 (§9 item 977)
}


def _p0(msg):
    if MPI.COMM_WORLD.rank == 0:
        print(msg, flush=True)


def _custody(prices, logs=LOGS) -> dict:
    """entry -> list of custody failures (empty = the ledger strings match the log).

    The log is read in whichever form retention left it (`.log` or `.log.gz`,
    §9 item 997); a missing or corrupt record raises.
    """
    out = {}
    for p in prices:
        lines = read_log_text(Path(logs) / p["log"], errors="strict").splitlines()
        bad = []
        elapsed = [ln.split(":", 1)[1].strip() for ln in lines if ln.startswith("- Elapsed (s):")]
        if elapsed != [p["seconds"]]:
            bad.append(f"seconds {p['seconds']} vs footer {elapsed}")
        idx = [i for i, ln in enumerate(lines) if ln.strip() == "[XL] memory.peak bytes:"]
        if len(idx) != 1:
            bad.append(f"memory.peak lines {len(idx)}")
        else:
            peak = int(lines[idx[0] + 1].strip())
            gib = f"{peak / 2**30:.2f}"
            if gib != p["gib"]:
                bad.append(f"GiB {p['gib']} vs log {gib} ({peak} B)")
        out[p["entry"]] = bad
    return out


def _ledger_with(tmp_path, old, new):
    text = gen.LEDGER.read_text(encoding="utf-8")
    assert text.count(old) == 1, old
    planted = tmp_path / "xl-ledger.md"
    planted.write_text(text.replace(old, new, 1), encoding="utf-8")
    return planted


def test_wf17_s47_ledger_strings_and_custody():
    prices = gen.ledger_prices()
    got = {p["entry"]: (p["ranks"], p["cells"], p["gib"], p["seconds"]) for p in prices}
    custody = _custody(prices)
    for p in prices:
        _p0(
            f"\n[WF-17 s47] (X-ledger) entry {p['entry']} {p['chunk']} `{p['log']}`: ranks "
            f"{p['ranks']!r} cells {p['cells']!r} GiB {p['gib']!r} seconds {p['seconds']!r}; "
            f"custody failures {custody[p['entry']]}"
        )
    assert [p["entry"] for p in prices] == ["58", "60", "61"]
    assert got == EXPECTED
    assert custody == {"58": [], "60": [], "61": []}


