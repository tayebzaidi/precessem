def test_wf17_s51_c61_custody_fails_on_entry61(tmp_path):
    text = gen.LEDGER.read_text(encoding="utf-8")
    row61 = next(
        ln for ln in text.splitlines() if ln.startswith("| 2026-11-12 | GEO-36-step11-I36-3T | ")
    )
    cells = row61.split(" | ")
    assert cells[6] == "848"
    cells[6] = "849"
    planted = _ledger_with(tmp_path, row61, " | ".join(cells))
    prices = gen.ledger_prices(planted)
    custody = _custody(prices)
    _p0(f"\n[WF-17 s51] (c-61) seconds {[p['seconds'] for p in prices]}; custody {custody}")
    assert [p["seconds"] for p in prices] == ["780", "732", "849"]
    assert custody["58"] == [] and custody["60"] == []
    assert custody["61"] and all("seconds" in b for b in custody["61"])


def test_wf17_s47_fc3_row_and_section():
    from fem_em_solver.study import PRICE_TABLE_CLINICAL_3T, ResourceEstimate

    comm = MPI.COMM_WORLD
    measured = gen.measured_3t(comm)
    row = measured["row"]
    est = row["est"]
    names = [f.name for f in dataclasses.fields(ResourceEstimate)]
    parsed = _parse(row["stdout"], names)
    complete = set(parsed) == set(names) and all(len(v) == 1 for v in parsed.values())
    differ = _diff(parsed, est) if complete else None
    rcs = comm.allgather(row["rc"])
    pin = PRICE_TABLE_CLINICAL_3T[-1]
    pr = row["printed"]
    _p0(
        f"\n[WF-17 s47] (K) {row['label']}: rc per rank {rcs}; complete={complete} "
        f"differ={differ}; rows_used={est.rows_used!r}; printed ranks {pr['ranks']!r} "
        f"seconds {pr['predicted_seconds']!r} GiB {pr['predicted_peak_gib']!r} "
        f"cells {pr['cells']!r}"
    )
    for r in measured["ratios"]:
        _p0(
            f"[WF-17 s47] ratio entry {r['entry']}: GiB {r['gib']} seconds {r['seconds']} "
            "(estimator / measured; a record)"
        )

    tracked = PAGE.read_text(encoding="utf-8")
    fresh = gen.render_measured(measured)
    pos = tracked.find(gen.MEASURED_HEADING)
    end = tracked.find("\n## ", pos + 1) if pos >= 0 else -1  # U163: the next `## ` heading or EOF
    section = (tracked[pos:end] if end >= 0 else tracked[pos:]) if pos >= 0 else ""
    _p0(
        f"[WF-17 s47] (Sec) heading at {pos}; section {len(section)} chars vs fresh "
        f"{len(fresh)}; equal={section == fresh}"
    )

    gates = {
        "K rc": rcs == [0] * comm.size,
        "K CLI=API": complete and differ == set(),
        "K rows_used": est.rows_used == ("FC3",),
        "K ranks": est.ranks == pin["ranks"],
        "K seconds": est.predicted_seconds == pin["seconds"],
        "K GiB": est.predicted_peak_gib == pin["peak_gib"],
        "K strings": (pr["ranks"], pr["predicted_seconds"], pr["predicted_peak_gib"])
        == (["16"], ["135.1"], ["39.39"]),
        "Sec": tracked.count(gen.MEASURED_HEADING) == 1 and section == fresh,
    }
    _p0(f"[WF-17 s47] gates {gates}")
    assert all(gates.values()), {k: v for k, v in gates.items() if not v}


