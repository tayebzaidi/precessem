"""`WF-17` step 54 (§9 item 1001, §10 U166): the measured 3 T degree-2 price on the estimates page.

Brief: docs/planning/chunks/WF-17.md, "§9 item 1001".  No mesh; run under
``mpiexec -n 2``.  The section is generated by
``scripts/docs/generate_estimate_page.py`` (``render_measured_3t_d2``) and sits between
the 3 T section and the degree-2 section of ``docs/guide/estimates.md``.

Asserted (no band set):
  (X-ledger-3d2) ``ledger_prices(LEDGER, entries=MEASURED_3T_D2)`` strings for `xl` entry
                 64; custody through the 3 T module's ``_custody``; the ledger prefix hit,
                 ``- Elapsed (s):`` and stripped-alone ``[XL] memory.peak bytes:`` counts
                 each 1.
  (Cells)        the ledger's cells equal ``F_CLINICAL_3T_R1_CELL_RECORD`` (by value).
  (K-4)          FC4 through the new fixture: rc 0 on every rank, ``rows_used == ()``, both
                 predictions NaN, unknowns == ``F_CLINICAL_3T_R1_UNKNOWNS_RECORD[1]``,
                 ``not_priced`` names degree 2, CLI = API **by printed string**
                 (``printed[name] == [repr(getattr(est, name))]``; never ``_diff``, whose
                 ``literal_eval`` cannot read ``nan``).
  (K-3)          FC3 unchanged: ``rows_used == ("FC3",)``, ``'16'`` / ``'135.1'`` /
                 ``'39.39'``, equal to ``PRICE_TABLE_CLINICAL_3T[-1]``.
  (Fix-3)        the fixture differs from ``f_clinical_3t.yaml`` on line 1 and the degree
                 line only.
  (Tag-3d2)      ``TAG403_3T_D2`` keys ``{"64"}``, ASCII, disjoint from the other tag dicts;
                 the anchored (G) regex has exactly one distinct match in entry 64's log.
  (Sec-3d2)      the tracked slice (heading to the next ``## ``) equals a fresh
                 ``render_measured_3t_d2(measured_3t_d2(comm))`` byte for byte.
  (Order-3d2)    1.5 T < 3 T < 3 T-d2 < d2 heading lines; four ``## `` lines, d2 last.
Negative controls (asserted): (c-64) entry 64's seconds 8158 -> 8159 in a tmp `xl` ledger
fails custody (seconds); (c-plant) a planted degree-2 3 T row prices FC4 (finite ratios,
``rows_used == ("PLANT4",)``); (c-d1) the fixture at degree 1 reads FC3.
"""

from __future__ import annotations

