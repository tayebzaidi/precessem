ROOT = Path(__file__).resolve().parent.parent.parent
PAGE = ROOT / "docs" / "guide" / "estimates.md"
LOGS = ROOT / "docs" / "testing" / "logs"
FC3T = ROOT / "tests" / "package" / "wf13" / "f_clinical_3t.yaml"

EXPECTED_3T_D2 = {"64": ("16", "1 057 895", "377.12", "8158")}
PREFIX_64 = "| 2026-11-15 | GEO-38-C5f | "
TAG_RE = re.compile(r"^\[GEO-38 C12\] \(G\) degree 2: .*tag 403 absent True")


def _log_lines():
    name = gen.ledger_prices(gen.LEDGER, entries=gen.MEASURED_3T_D2)[0]["log"]
    # `.log` or `.log.gz`, whichever retention left (§9 item 997's shared reader).
    return read_log_text(LOGS / name, errors="strict").splitlines()


def _printed_vs_repr(row):
    from fem_em_solver.study import ResourceEstimate

    est, pr = row["est"], row["printed"]
    names = [f.name for f in dataclasses.fields(ResourceEstimate)]
    return {n for n in names if pr.get(n) != [repr(getattr(est, n))]}


def test_wf17_s54_ledger_strings_and_custody():
    hits = [i + 1 for i, ln in enumerate(gen.LEDGER.read_text(encoding="utf-8").splitlines())
            if ln.startswith(PREFIX_64)]
    prices = gen.ledger_prices(gen.LEDGER, entries=gen.MEASURED_3T_D2)
    got = {p["entry"]: (p["ranks"], p["cells"], p["gib"], p["seconds"]) for p in prices}
    custody = _custody(prices)
    lines = _log_lines()
    n_elapsed = sum(ln.startswith("- Elapsed (s):") for ln in lines)
    n_peak = sum(ln.strip() == "[XL] memory.peak bytes:" for ln in lines)
    for p in prices:
        _p0(f"\n[WF-17 s54] (X-ledger-3d2) entry {p['entry']} {p['chunk']} `{p['log']}`: ranks "
            f"{p['ranks']!r} cells {p['cells']!r} GiB {p['gib']!r} seconds {p['seconds']!r}; "
            f"prefix hits {len(hits)} at {hits}; Elapsed lines {n_elapsed}; memory.peak lines "
            f"{n_peak}; custody failures {custody[p['entry']]}")
    assert len(hits) == 1
    assert [p["entry"] for p in prices] == ["64"]
    assert got == EXPECTED_3T_D2
    assert custody == {"64": []}
    assert n_elapsed == 1 and n_peak == 1


