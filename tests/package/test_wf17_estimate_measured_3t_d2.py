def test_wf17_s54_fc4_and_fc3_rows():
    from fem_em_solver.study import (
        F_CLINICAL_3T_R1_UNKNOWNS_RECORD,
        PRICE_TABLE_CLINICAL_3T,
    )

    comm = MPI.COMM_WORLD
    m = gen.measured_3t_d2(comm)
    fc4, fc3 = m["fc4"]["row"], m["fc3"]["row"]
    e4, e3 = fc4["est"], fc3["est"]
    rc4, rc3 = comm.allgather(fc4["rc"]), comm.allgather(fc3["rc"])
    d4, d3 = _printed_vs_repr(fc4), _printed_vs_repr(fc3)
    pin = PRICE_TABLE_CLINICAL_3T[-1]
    pr3 = fc3["printed"]
    _p0(f"\n[WF-17 s54] (K-4) {fc4['label']}: rc per rank {rc4}; printed-vs-repr differ {d4}; "
        f"{e4!r}")
    _p0(f"[WF-17 s54] (K-3) {fc3['label']}: rc per rank {rc3}; printed-vs-repr differ {d3}; "
        f"{e3!r}")
    for name, mm in (("FC4", m["fc4"]), ("FC3", m["fc3"])):
        r = mm["ratios"][0]
        _p0(f"[WF-17 s54] ratio {name} / entry {r['entry']}: GiB {r['gib']} seconds "
            f"{r['seconds']} (estimator / measured; a record; predicted "
            f"{ {'FC4': 'nan / nan', 'FC3': '0.1044 / 0.0166'}[name] })")
    gates = {
        "K-4 rc": rc4 == [0] * comm.size,
        "K-4 rows_used": e4.rows_used == (),
        "K-4 nan": math.isnan(e4.predicted_peak_gib) and math.isnan(e4.predicted_seconds),
        "K-4 unknowns": e4.unknowns == 7_335_988 == F_CLINICAL_3T_R1_UNKNOWNS_RECORD[1],
        "K-4 not_priced": any("degree 2" in s for s in e4.not_priced),
        "K-4 CLI=API": d4 == set(),
        "K-3 rc": rc3 == [0] * comm.size,
        "K-3 rows_used": e3.rows_used == ("FC3",),
        "K-3 strings": (pr3["ranks"], pr3["predicted_seconds"], pr3["predicted_peak_gib"])
        == (["16"], ["135.1"], ["39.39"]),
        "K-3 table": (float(e3.ranks), float(e3.predicted_seconds), float(e3.predicted_peak_gib))
        == (float(pin["ranks"]), float(pin["seconds"]), float(pin["peak_gib"])),
        "K-3 CLI=API": d3 == set(),
    }
    _p0(f"[WF-17 s54] gates {gates}")
    assert all(gates.values()), {k: v for k, v in gates.items() if not v}


