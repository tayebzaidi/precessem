def test_wf17_s53_c_gz_d2(tmp_path, monkeypatch):
    """(c-gz-d2), §9 item 998: entry 62's log read from a gzip-only directory equals the
    tracked read line for line and keeps (Call) green; an empty directory raises (the
    13:30 2026-11-15 defect: a plain-only reader after the 7-day sweep)."""
    import sys

    module = sys.modules[__name__]
    name = _log_name()
    plain = _log_lines()
    gzdir = tmp_path / "gz"
    gzdir.mkdir()
    with gzip.open(gzdir / f"{name}.gz", "wt", encoding="utf-8") as fh:
        fh.write(read_log_text(LOGS / name, errors="strict"))
    assert not (gzdir / name).exists()
    monkeypatch.setattr(module, "LOGS", gzdir)
    zipped = _log_lines()
    check = _call_check(gen.ledger_calls(), zipped)
    _p0(
        f"\n[WF-17 s53] (c-gz-d2) {name}: tracked {len(plain)} lines, gzip-only {len(zipped)} "
        f"lines, equal={zipped == plain}; (Call) on the gzip read {check}"
    )
    assert zipped == plain
    assert check == {"62 call 1": [], "62 call 2": []}

    empty = tmp_path / "empty"
    empty.mkdir()
    monkeypatch.setattr(module, "LOGS", empty)
    with pytest.raises(FileNotFoundError) as err:
        _log_lines()
    _p0(f"[WF-17 s53] (c-gz-d2) separation, empty dir: {type(err.value).__name__}")
