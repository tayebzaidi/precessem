def _xxl_ledger_with(tmp_path, old, new):
    text = gen.XXL_LEDGER.read_text(encoding="utf-8")
    assert text.count(old) == 1, old
    planted = tmp_path / "xxl-ledger.md"
    planted.write_text(text.replace(old, new, 1), encoding="utf-8")
    return planted


def _log_name():
    return gen.ledger_prices(gen.XXL_LEDGER, entries=gen.MEASURED_D2)[0]["log"]


def _log_lines():
    # (G2, §9 item 998): entry 62's log in whichever form retention left it
    # (`.log` or `.log.gz`), through item 997's shared reader; missing or corrupt raises.
    return read_log_text(Path(LOGS) / _log_name(), errors="strict").splitlines()


def _call_check(calls, lines) -> dict:
    """call key -> list of (Call) failures against the log (empty = custody holds)."""
    out = {}
    for c in calls:
        bad = []
        prefix = CALL_PREFIX[c["key"]]
        n = int(c["line"])
        line = lines[n - 1] if 0 < n <= len(lines) else ""
        if not line.startswith(prefix):
            bad.append(f"line {n} does not start with {prefix!r}")
        want = f"window {c['seconds'].replace(' ', '')} s"
        if want not in line:
            bad.append(f"line {n} lacks {want!r}")
        hits = [i + 1 for i, ln in enumerate(lines) if ln.startswith(prefix)]
        if hits != [n]:
            bad.append(f"prefix lines {hits}")
        out[c["key"]] = bad
    return out


def _row_tracked():
    return [
        ln
        for ln in gen.XXL_LEDGER.read_text(encoding="utf-8").splitlines()
        if ln.startswith("| 2026-11-14 | GEO-38-C19 | ")
    ]


def test_wf17_s53_ledger_strings_and_custody():
    prices = gen.ledger_prices(gen.XXL_LEDGER, entries=gen.MEASURED_D2)
    got = {p["entry"]: (p["ranks"], p["cells"], p["gib"], p["seconds"]) for p in prices}
    custody = _custody(prices)
    for p in prices:
        _p0(
            f"\n[WF-17 s53] (X-ledger-d2) window: entry {p['entry']} {p['chunk']} `{p['log']}`: "
            f"ranks {p['ranks']!r} cells {p['cells']!r} GiB {p['gib']!r} seconds "
            f"{p['seconds']!r}; custody failures {custody[p['entry']]}"
        )
    assert [p["entry"] for p in prices] == ["62"]
    assert got == EXPECTED_D2
    assert custody == {"62": []}


