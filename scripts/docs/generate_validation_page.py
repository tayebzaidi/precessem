#!/usr/bin/env python3
"""Generate ``docs/guide/validation.md`` from the WF-14 registry (WF-14 step 2).

One section per name in ``fem_em_solver.__all__`` (in ``public_names()`` order,
reused from ``generate_api_reference.py`` by import): a link to the name's API
page, the gating chunk IDs, and a ``| Node | Chunk | Bands |`` table over the
name's registry nodes (``tests/package/validation_envelope.toml``) in registry
order.

* **Chunk IDs** come from the node module's docstring: the backticked
  ``ABC-12`` IDs of its first paragraph, else of the whole docstring. A module
  whose docstring names none takes its IDs from ``CHUNK_OVERRIDES`` below (one
  line per module, each citing the plan record it was attributed from). Every
  ID must be a ``PROJECT_PLAN.md`` §7 row.
* **Bands** are read with ``ast`` only (no test module is imported): every
  ``Name`` / ``Attribute.attr`` in the node function's body matching
  ``BAND_RE`` that resolves to a top-level assignment of the module, or of the
  module one ``from X import NAME`` hop away. Bands asserted inside fixtures or
  helpers are not traced (v0).

Refusals (exit 1, nothing written): (F1) a public name with no registry
entry; (F2) a node whose module yields no chunk ID; (F3) a derived ID with no
§7 row.

    python3 scripts/docs/generate_validation_page.py --out docs/guide/validation.md
    python3 scripts/docs/generate_validation_page.py --out docs/guide/validation.md --check
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import os
import re
import sys
import tempfile
from functools import lru_cache
from pathlib import Path

_API_GEN_PATH = Path(__file__).resolve().parent / "generate_api_reference.py"


def _load_api_generator():
    spec = importlib.util.spec_from_file_location("wf14_s2_generate_api_reference", _API_GEN_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_api = _load_api_generator()
public_names = _api.public_names
load_registry = _api.load_registry
REPO_ROOT = _api.REPO_ROOT

PLAN_PATH = REPO_ROOT / "PROJECT_PLAN.md"
DEFAULT_OUT = REPO_ROOT / "docs" / "guide" / "validation.md"
HEADER = (
    "<!-- GENERATED by scripts/docs/generate_validation_page.py from "
    "fem_em_solver.__all__ and tests/package/validation_envelope.toml. "
    "Do not edit; regenerate. -->"
)
ID_RE = re.compile(r"`([A-Z]+-\d+)`")
BAND_RE = re.compile(r"^[A-Z][A-Z0-9_]*_(BAND|RTOL|ATOL|TOLERANCE|FLOOR|CEILING)$")
NO_BAND = "— (structural / inline; see node)"

# Modules whose docstring names no §7 ID, attributed from the plan record.
CHUNK_OVERRIDES: dict[str, tuple[str, ...]] = {
    # PROJECT_PLAN §7 PORT-7 row: "existing `test_touchstone_export.py` green unedited (rule (c))" in the PORT-7 W2 close.
    "tests/io/test_touchstone_export.py": ("PORT-7",),
    # docs/planning/chunks/MAT-1.md: "✅ 2026-09-29 ... `tests/materials/test_phantom_material_model.py` landed with the re-anchored premise".
    "tests/materials/test_phantom_material_model.py": ("MAT-1",),
    # docs/planning/chunks/OPS-56.md: the sweep-planner chunk's record cites this file's exact-equality asserts (:101, :107–109, ...).
    "tests/ports/test_frequency_sweep_planner.py": ("OPS-56",),
    # docs/planning/chunks/PORT-2.md:125: "`tests/ports/test_port_definition.py` is green in the same window ⇒ 🧪 → ✅".
    "tests/ports/test_port_definition.py": ("PORT-2",),
    # docs/planning/chunks/PORT-5.md (§9 item 98 close): "tests only, `tests/ports/test_sparameter_assembly.py`".
    "tests/ports/test_sparameter_assembly.py": ("PORT-5",),
    # docs/planning/chunks/GEO-23.md step 2b ⇒ chunk ✅: the rank-dependent census red in this file made green (0.04 → 0.032).
    "tests/solver/test_boundary_condition_selection.py": ("GEO-23",),
    # PROJECT_PLAN §7 TH-4 row: Done-when written "on `tests/solver/test_convergence_diagnostics.py`'s fixture".
    "tests/solver/test_convergence_diagnostics.py": ("TH-4",),
}


class GenerationError(RuntimeError):
    """A refusal (F1)-(F3); the message names the offender."""


# ------------------------------------------------------------------ sources
@lru_cache(maxsize=None)
def _parse(repo_rel: str) -> ast.Module:
    return ast.parse((REPO_ROOT / repo_rel).read_text(encoding="utf-8"), filename=repo_rel)


@lru_cache(maxsize=None)
def plan_rows() -> frozenset[str]:
    text = PLAN_PATH.read_text(encoding="utf-8")
    return frozenset(re.findall(r"^\| `([A-Z]+-\d+)` \|", text, flags=re.MULTILINE))


def module_chunk_ids(repo_rel: str, overrides: dict[str, tuple[str, ...]] | None = None) -> tuple[str, ...]:
    overrides = CHUNK_OVERRIDES if overrides is None else overrides
    doc = ast.get_docstring(_parse(repo_rel)) or ""
    ids = ID_RE.findall(doc.split("\n\n", 1)[0]) or ID_RE.findall(doc)
    if not ids:
        ids = list(overrides.get(repo_rel, ()))
    return tuple(sorted(set(ids)))


def _top_level_assigns(tree: ast.Module) -> dict[str, ast.expr]:
    out: dict[str, ast.expr] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign):
            for t in stmt.targets:
                if isinstance(t, ast.Name):
                    out[t.id] = stmt.value
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value is not None:
            out[stmt.target.id] = stmt.value
    return out


def _from_imports(tree: ast.Module, repo_rel: str) -> dict[str, str]:
    """NAME -> repo-relative file of a top-level ``from X import NAME`` (in-repo only)."""
    out: dict[str, str] = {}
    here = Path(repo_rel).parent
    for stmt in tree.body:
        if not isinstance(stmt, ast.ImportFrom) or stmt.module is None and stmt.level == 0:
            continue
        parts = (stmt.module or "").split(".") if stmt.module else []
        if stmt.level:
            base = here
            for _ in range(stmt.level - 1):
                base = base.parent
            cand = base.joinpath(*parts)
        else:
            cand = Path(*parts)
        for c in (cand.with_suffix(".py"), Path("src") / cand.with_suffix(".py")):
            if (REPO_ROOT / c).is_file():
                for alias in stmt.names:
                    out[alias.asname or alias.name] = (c.as_posix(), alias.name)
                break
    return out


def resolve_band(repo_rel: str, name: str):
    """(defining file, NAME, rendered text) or None if NAME is no module-level band."""
    tree = _parse(repo_rel)
    assigns = _top_level_assigns(tree)
    if name in assigns:
        file, rhs = repo_rel, assigns[name]
    else:
        hop = _from_imports(tree, repo_rel).get(name)
        if hop is None:
            return None
        file, orig = hop
        rhs = _top_level_assigns(_parse(file)).get(orig)
        if rhs is None:
            return None
        name = orig
    try:
        ast.literal_eval(rhs)
        text = f"{name} = {ast.unparse(rhs)}"
    except (ValueError, TypeError, SyntaxError, MemoryError, RecursionError):
        text = f"{name} (computed)"
    return file, name, text


def _function(tree: ast.Module, func: str):
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and stmt.name == func:
            return stmt
    return None


def node_bands(node: str) -> list[tuple[str, str, str]]:
    repo_rel, _, func = node.partition("::")
    func = func.split("[", 1)[0]
    fn = _function(_parse(repo_rel), func)
    if fn is None:
        return []
    seen: list[str] = []
    for sub in ast.walk(fn):
        ident = sub.id if isinstance(sub, ast.Name) else sub.attr if isinstance(sub, ast.Attribute) else None
        if ident and BAND_RE.match(ident) and ident not in seen:
            seen.append(ident)
    out = []
    for ident in sorted(seen):
        r = resolve_band(repo_rel, ident)
        if r is not None:
            out.append(r)
    return out


# --------------------------------------------------------------------- page
def _from_guide(repo_rel: str) -> str:
    return "../../" + repo_rel


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def build(names=None, registry=None, overrides=None) -> tuple[str, dict]:
    names = public_names() if names is None else list(names)
    registry = load_registry() if registry is None else registry
    missing = [n for n in names if n not in registry]
    if missing:
        raise GenerationError(f"(F1) public name(s) with no registry entry: {missing}")
    rows = plan_rows()
    stats = {"nodes": 0, "with_band": 0, "without_band": 0, "computed": 0, "bands": 0}
    lines = [
        HEADER,
        "",
        "# Validation envelope",
        "",
        "Every name in `fem_em_solver.__all__` with the gate test nodes that cover it, as "
        "listed in the `WF-14` registry (`tests/package/validation_envelope.toml`), the "
        "chunk IDs those nodes' modules name, and the module-level bands each node "
        "function references. Listed is not the same as green today: only collectability "
        "of the nodes is asserted. Bands asserted inside fixtures or helpers are not "
        "traced; such a node reads \"structural / inline\".",
        "",
    ]
    for name in names:
        nodes = list(registry[name].get("nodes", []))
        table = ["| Node | Chunk | Bands |", "| --- | --- | --- |"]
        all_ids: set[str] = set()
        for node in nodes:
            repo_rel = node.split("::", 1)[0]
            ids = module_chunk_ids(repo_rel, overrides)
            if not ids:
                raise GenerationError(f"(F2) node whose module yields no chunk ID: {node}")
            bad = [i for i in ids if i not in rows]
            if bad:
                raise GenerationError(f"(F3) chunk ID(s) with no §7 row: {bad} (from {node})")
            all_ids.update(ids)
            bands = node_bands(node)
            stats["nodes"] += 1
            stats["with_band" if bands else "without_band"] += 1
            stats["bands"] += len(bands)
            stats["computed"] += sum(t.endswith("(computed)") for _, _, t in bands)
            band_cell = (
                "<br>".join(f"`{_cell(t)}` ([{Path(f).name}]({_from_guide(f)}))" for f, _, t in bands)
                if bands
                else NO_BAND
            )
            table.append(
                f"| [`{_cell(node)}`]({_from_guide(repo_rel)}) | "
                f"{', '.join(f'`{i}`' for i in ids)} | {band_cell} |"
            )
        lines += [
            f"### {name}",
            "",
            f"API page: [{name}](api/{name}.md)",
            "",
            "Gating chunks: " + ", ".join(f"`{i}`" for i in sorted(all_ids)),
            "",
            *table,
            "",
        ]
    return "\n".join(line.rstrip() for line in lines), stats


def generate(out: Path, **kw) -> dict:
    text, stats = build(**kw)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return stats


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output file")
    parser.add_argument("--check", action="store_true", help="diff against --out, exit 1 on change")
    args = parser.parse_args(argv)
    out = Path(args.out)
    if not out.is_absolute():
        out = Path(os.getcwd()) / out
    try:
        if args.check:
            with tempfile.TemporaryDirectory() as tmp:
                fresh = Path(tmp) / "validation.md"
                generate(fresh)
                same = out.is_file() and fresh.read_bytes() == out.read_bytes()
            print(f"Validation page check: {'identical' if same else 'DIFFERS'}: {out.name}")
            return 0 if same else 1
        stats = generate(out)
    except GenerationError as exc:
        print(f"Validation page: refused: {exc}")
        return 1
    print(f"Validation page: wrote {out.name}; stats={stats}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
