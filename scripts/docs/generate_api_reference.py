#!/usr/bin/env python3
"""Generate the API reference pages under ``docs/guide/api/`` (WF-17 step 2).

One Markdown page per name in ``fem_em_solver.__all__`` plus an ``index.md``.
Each page carries the name's kind, its ``inspect.signature`` text (memory
addresses scrubbed), its docstring verbatim in a fenced ``text`` block, a
relative link to the defining source file, and its WF-14 envelope entry
(``tests/package/validation_envelope.toml``) as a "Validated by" list of gate
node IDs between ``<!-- envelope:begin -->`` / ``<!-- envelope:end -->``.

The pages are generated, never hand-edited:

    python3 scripts/docs/generate_api_reference.py --out docs/guide/api
    python3 scripts/docs/generate_api_reference.py --out docs/guide/api --check

``--check`` generates into a temporary directory and exits 1 if the committed
tree differs (file set or bytes). Output is deterministic: sorted names, ``\\n``
line endings. No validation claim is made here beyond what the registry lists;
collectability of the listed nodes is asserted by
``tests/package/test_wf17_api_reference.py``.
"""

from __future__ import annotations

import argparse
import inspect
import os
import re
import sys
import tempfile
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
REGISTRY_PATH = REPO_ROOT / "tests" / "package" / "validation_envelope.toml"
DEFAULT_OUT = REPO_ROOT / "docs" / "guide" / "api"
HEADER = (
    "<!-- GENERATED by scripts/docs/generate_api_reference.py from "
    "fem_em_solver.__all__ and tests/package/validation_envelope.toml. "
    "Do not edit; regenerate. -->"
)
ENVELOPE_BEGIN = "<!-- envelope:begin -->"
ENVELOPE_END = "<!-- envelope:end -->"
_ADDRESS_RE = re.compile(r" at 0x[0-9a-fA-F]+")


def _package():
    import fem_em_solver

    return fem_em_solver


def public_names() -> list[str]:
    pkg = _package()
    names = sorted(set(pkg.__all__))
    for n in names:
        getattr(pkg, n)  # a dangling __all__ entry raises here
    return names


def load_registry() -> dict[str, dict]:
    with REGISTRY_PATH.open("rb") as fh:
        return dict(tomllib.load(fh).get("names", {}))


def _kind(obj) -> str:
    if inspect.isclass(obj):
        return "exception" if issubclass(obj, BaseException) else "class"
    if inspect.isfunction(obj) or inspect.isbuiltin(obj):
        return "function"
    return type(obj).__name__


def _signature(name: str, obj) -> str:
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(signature unavailable)"
    return _ADDRESS_RE.sub("", f"{name}{sig}")


def _fence_for(text: str) -> str:
    fence = "```"
    while fence in text:
        fence += "`"
    return fence


def _rel_to_page(repo_rel: str) -> str:
    """A repo-relative path, as seen from a page in ``docs/guide/api/``."""
    return "../../../" + repo_rel


def _source_rel(obj) -> str:
    src = inspect.getsourcefile(obj)
    if src is None:
        raise RuntimeError(f"no source file for {obj!r}")
    path = Path(src).resolve()
    root = REPO_ROOT.resolve()
    if root not in path.parents:
        raise RuntimeError(
            f"{obj!r} is defined in {path}, outside the repo {root}: an installed "
            "copy would make the source link dead on another box (WF-13)"
        )
    return path.relative_to(root).as_posix()


def render(name: str, registry: dict[str, dict] | None = None) -> str:
    registry = load_registry() if registry is None else registry
    obj = getattr(_package(), name)
    doc = inspect.getdoc(obj)
    src = _source_rel(obj)
    nodes = list(registry.get(name, {}).get("nodes", []))

    lines = [HEADER, "", f"# {name}", "", f"**Kind:** {_kind(obj)}", ""]
    sig = _signature(name, obj)
    fence = _fence_for(sig)
    lines += ["## Signature", "", f"{fence}python", sig, fence, ""]
    lines += ["## Docstring", ""]
    if doc:
        fence = _fence_for(doc)
        lines += [f"{fence}text", *doc.splitlines(), fence, ""]
    else:
        lines += ["*(no docstring)*", ""]
    lines += ["## Source", "", f"Defined in [`{src}`]({_rel_to_page(src)}).", ""]
    lines += ["## Validated by", "", ENVELOPE_BEGIN]
    for node in nodes:
        node_file = node.split("::", 1)[0]
        lines.append(f"- `{node}` ([{Path(node_file).name}]({_rel_to_page(node_file)}))")
    lines += [ENVELOPE_END, ""]
    lines += [
        "Listed nodes are the `WF-14` envelope entry for this name; only their "
        "collectability is asserted, not that they are green today.",
        "",
        "[Back to the API index](index.md)",
        "",
    ]
    return "\n".join(line.rstrip() for line in lines)


def render_index(names: list[str]) -> str:
    lines = [
        HEADER,
        "",
        "# API reference",
        "",
        "One page per name in `fem_em_solver.__all__`, each with its signature, "
        "docstring and `WF-14` validation-envelope entry.",
        "",
    ]
    for n in names:
        lines.append(f"- [{n}]({n}.md)")
    lines.append("")
    return "\n".join(lines)


def expected_files() -> dict[str, str]:
    registry = load_registry()
    names = public_names()
    files = {f"{n}.md": render(n, registry) for n in names}
    files["index.md"] = render_index(names)
    return files


def generate(out_dir: Path) -> list[str]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    files = expected_files()
    for stale in sorted(out_dir.glob("*.md")):
        if stale.name not in files and stale.read_text().startswith(HEADER):
            stale.unlink()
    for fname in sorted(files):
        with open(out_dir / fname, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(files[fname])
    return sorted(files)


def diff_trees(a: Path, b: Path) -> list[str]:
    """File names (``*.md``) whose presence or bytes differ between two trees."""
    fa = {p.name: p for p in Path(a).glob("*.md")}
    fb = {p.name: p for p in Path(b).glob("*.md")}
    out = []
    for name in sorted(set(fa) | set(fb)):
        if name not in fa or name not in fb or fa[name].read_bytes() != fb[name].read_bytes():
            out.append(name)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output directory")
    parser.add_argument("--check", action="store_true", help="diff against --out, exit 1 on change")
    args = parser.parse_args(argv)
    out = Path(args.out)
    if not out.is_absolute():
        out = Path(os.getcwd()) / out
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            generate(Path(tmp))
            diff = diff_trees(Path(tmp), out)
        print(f"API reference check: {len(diff)} differing file(s): {diff}")
        return 1 if diff else 0
    written = generate(out)
    print(f"API reference: wrote {len(written)} file(s) to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
